def select_next_two(state: dict) -> list[dict]:
    history = state.get("history", [])
    used_counts = {a["key"]: 0 for a in ARTICLES}
    last_used_idx = {a["key"]: -1 for a in ARTICLES}
    for idx, h in enumerate(history):
        k = h.get("key")
        if k in used_counts:
            used_counts[k] += 1
            last_used_idx[k] = idx

    # Sort by (times used ascending, last used index ascending) so unused articles are picked first, then oldest
    sorted_articles = sorted(
        ARTICLES,
        key=lambda a: (used_counts[a["key"]], last_used_idx[a["key"]]),
    )
    return sorted_articles[:2]


