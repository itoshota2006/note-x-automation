def find_chrome() -> str:
    for b in ("google-chrome", "google-chrome-stable", "chromium-browser", "chromium"):
        p = shutil.which(b)
        if p:
            return p
    for mac_path in (
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
    ):
        if Path(mac_path).exists():
            return mac_path
    raise RuntimeError("Chrome binary not found")


def render_png(html_path: Path, png_path: Path) -> None:
    chrome = find_chrome()
    subprocess.run(
        [
            chrome,
            "--headless=new",
            "--no-sandbox",
            "--disable-gpu",
            "--disable-dev-shm-usage",
            "--ignore-certificate-errors",
            "--hide-scrollbars",
            "--window-size=1200,900",
            "--force-device-scale-factor=2",
            f"--screenshot={png_path}",
            f"file://{html_path}",
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def send_email(subject: str, body_path: Path, attachments: list[Path]) -> str:
    # 1. If running in Antigravity VM with `gmail` plugin CLI available, try it first
    gmail_cli = shutil.which("gmail")
    if gmail_cli and not os.environ.get("GITHUB_ACTIONS"):
        file_args: list[str] = []
        for att in attachments:
            if att.exists():
                file_args.extend(["--file", str(att)])
        cmd_sub = "send-with-attachment" if file_args else "send"
        res = subprocess.run(
            [
                gmail_cli,
                "mutate",
                cmd_sub,
                "--to",
                RECIPIENT,
                "--subject",
                subject,
                "--body-file",
                str(body_path),
                *file_args,
            ],
            capture_output=True,
            text=True,
        )
        if res.returncode == 0:
            return "sent_via_gmail_plugin"
        # Fallback to create-draft if AGY_UNATTENDED blocks send
        res_draft = subprocess.run(
            [
                gmail_cli,
                "mutate",
                "create-draft",
                "--to",
                RECIPIENT,
                "--subject",
                subject,
                "--body-file",
                str(body_path),
                *file_args,
            ],
            capture_output=True,
            text=True,
        )
        if res_draft.returncode == 0:
            return "draft_created_via_gmail_plugin"

    # 2. Send via Gmail SMTP SSL using App Password (works in GitHub Actions and anywhere with SMTP access)
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = RECIPIENT
    msg["To"] = RECIPIENT
    msg.set_content(body_path.read_text(encoding="utf-8"))

    for att in attachments:
        if not att.exists():
            continue
        img_bytes = att.read_bytes()
        msg.add_attachment(
            img_bytes,
            maintype="image",
            subtype="png",
            filename=att.name,
        )

    with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=30) as smtp:
        smtp.login(RECIPIENT, GMAIL_APP_PASSWORD)
        smtp.send_message(msg)
    return "sent_via_smtp_ssl"


def load_paid_article_keys(base_dir: Path) -> set[str]:
    """Parse past_articles.md summary table and return article keys marked as paid or paid-funnel."""
    paid_keys: set[str] = set()
    md_path = base_dir / "past_articles.md"
    if not md_path.exists():
        return paid_keys
    for line in md_path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            continue
        cols = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cols) < 4:
            continue
        key_match = re.search(r"n[0-9a-z]{8,}", cols[1])
        if not key_match:
            continue
        pricing_col = cols[3]
        if "有料" in pricing_col:
            paid_keys.add(key_match.group(0))
    return paid_keys


def is_article_paid_or_funnel(art: dict, paid_keys: set[str]) -> bool:
    if art.get("is_paid"):
        return True
    if art.get("key") in paid_keys:
        return True
    title = str(art.get("title") or "")
    post = str(art.get("post") or "")
    if "有料" in title or "有料" in post or "実践編" in title:
        return True
    return False


